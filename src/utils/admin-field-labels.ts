export function adminFieldLabel(path: string, locale: string): string {
	if (paths[path]) return i18n(paths[path] as I18nKey, locale);
	return path
		.replace(/\[\d+\]/g, "")
		.split(".")
		.filter((_part, index) => index > 0 || !path.includes("."))
		.map((part) => (names[part] ? i18n(names[part] as I18nKey, locale) : part))
		.join(" · ");
}
export function adminOptionLabel(
	value: string,
	locale: string,
	path = "",
): string {
	if (value === "auto") return i18n(I18nKey.adminOptionAuto, locale);
	if (path === "commentConfig.giscus.mapping") {
		const mappings: Record<string, I18nKey> = {
			pathname: I18nKey.adminOptionPathname,
			url: I18nKey.adminOptionFullUrl,
			title: I18nKey.adminOptionTitle,
			"og:title": I18nKey.adminOptionOgTitle,
			specific: I18nKey.adminOptionSpecific,
			number: I18nKey.adminOptionNumber,
		};
		if (mappings[value]) return i18n(mappings[value], locale);
	}
	const key =
		values[value] ??
		names[value] ??
		names[value.replace(/^./, (character) => character.toUpperCase())];
	return key ? i18n(key as I18nKey, locale) : value;
}

